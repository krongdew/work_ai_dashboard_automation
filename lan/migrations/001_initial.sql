PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY, username TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY, owner TEXT NOT NULL,
    csrf TEXT NOT NULL, expires REAL NOT NULL);
CREATE TABLE IF NOT EXISTS pairing(token TEXT PRIMARY KEY, owner TEXT NOT NULL, expires REAL NOT NULL);
CREATE TABLE IF NOT EXISTS workers(id TEXT PRIMARY KEY, owner TEXT NOT NULL,
    token TEXT UNIQUE NOT NULL, model TEXT NOT NULL, seen REAL NOT NULL, active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS tasks(id TEXT PRIMARY KEY, owner TEXT NOT NULL,
    payload TEXT NOT NULL, status TEXT NOT NULL, worker TEXT, lease TEXT,
    expires REAL NOT NULL, result TEXT, error TEXT);
CREATE INDEX IF NOT EXISTS tasks_owner_status ON tasks(owner,status);
CREATE TABLE IF NOT EXISTS login_attempts(key TEXT PRIMARY KEY, failures INTEGER NOT NULL, since REAL NOT NULL);
